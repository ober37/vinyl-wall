// Writes cdn-lock.json: the jsdelivr URLs the page loads React and appica from, and an import map that sends every
// version of each library in their dependency graph to one version, so there's one React (and one Base UI, one Motion).
// jsdelivr pins each package's own dependencies when it builds its +esm files, and different packages pinned different
// React versions; without the map the page loads several Reacts and hooks break. Run after changing a version here or
// adding an appica component: `npm run cdn:lock`. Needs the network; the build itself only reads the lock.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const CDN = 'https://cdn.jsdelivr.net'
// the versions the app is written against; everything else follows from jsdelivr's graph
const PIN = { react: '19.3.0', 'react-dom': '19.3.0', '@appica/ui-react': '1.3.0' }
const src = join(import.meta.dirname, '../src')
const files = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? files(join(d, e.name)) : [join(d, e.name)]))

// what the app imports (not tests)
const subs = new Set()
for (const f of files(src).filter((f) => /\.tsx?$/.test(f) && !/\.test\./.test(f)))
  for (const m of readFileSync(f, 'utf8').matchAll(/from '@appica\/ui-react\/([a-z/-]+)'/g)) subs.add(m[1])
const entries = {
  react: `/npm/react@${PIN.react}/+esm`,
  'react/jsx-runtime': `/npm/react@${PIN.react}/jsx-runtime/+esm`,
  'react-dom/client': `/npm/react-dom@${PIN['react-dom']}/client/+esm`,
  ...Object.fromEntries([...subs].sort().map((s) => [`@appica/ui-react/${s}`, `/npm/@appica/ui-react@${PIN['@appica/ui-react']}/${s}/+esm`])),
}

// crawl every module the entries reach
const seen = new Map() // path -> resolved path (after redirects)
const queue = Object.values(entries)
while (queue.length) {
  const p = queue.shift()
  if (seen.has(p)) continue
  const res = await fetch(CDN + p)
  if (!res.ok) throw new Error(`${res.status} ${p}`)
  const resolved = new URL(res.url).pathname
  seen.set(p, resolved)
  const body = await res.text()
  for (const m of body.matchAll(/(?:from|import)\s*\(?\s*"(\/npm\/[^"]+)"/g)) queue.push(m[1])
}

// every package@version seen, by package
const pkgOf = (p) => /^\/npm\/((?:@[^/]+\/)?[^@/]+)@([^/]+)\//.exec(decodeURIComponent(p))
const versions = new Map()
for (const p of [...seen.keys(), ...seen.values()]) {
  const m = pkgOf(p)
  if (!m) continue
  if (!versions.has(m[1])) versions.set(m[1], new Set())
  versions.get(m[1]).add(m[2])
}
const exact = (v) => /^\d+\.\d+\.\d+$/.test(v)
const cmp = (a, b) => a.split('.').map(Number).reduce((r, x, i) => r || x - b.split('.').map(Number)[i], 0)
const imports = {}
const chosen = {}
for (const [pkg, vs] of [...versions].sort()) {
  const ex = [...vs].filter(exact).sort(cmp)
  const pick = PIN[pkg] || ex[ex.length - 1]
  if (!pick) throw new Error(`no exact version of ${pkg}: ${[...vs]}`)
  for (const v of ex) if (v.split('.')[0] !== pick.split('.')[0]) throw new Error(`${pkg}: ${v} and ${pick} differ in major version`)
  chosen[pkg] = pick
  for (const v of vs) if (v !== pick) imports[`${CDN}/npm/${pkg}@${encodeURIComponent(v).replace(/%40/g, '@')}/`] = `${CDN}/npm/${pkg}@${pick}/`
}

writeFileSync(
  join(import.meta.dirname, '../cdn-lock.json'),
  JSON.stringify({ note: 'Generated by scripts/cdn-lock.mjs; commit it.', entries: Object.fromEntries(Object.entries(entries).map(([k, v]) => [k, CDN + v])), chosen, importMap: { imports } }, null, 2) + '\n',
)
console.log(`${seen.size} modules, ${Object.keys(chosen).length} packages, ${Object.keys(imports).length} remapped versions`)
for (const [pkg, vs] of versions) if (vs.size > 1) console.log(' ', pkg, [...vs].join(' '), '->', chosen[pkg])
